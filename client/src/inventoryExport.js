function wrapHtml(title, body, company = DEFAULT_COMPANY) {
  const c = company || DEFAULT_COMPANY;
  const logo = safeLogoHtml(c);
  const address = [c.addressLine1, c.addressLine2, c.city].filter(Boolean).map(escapeHtml).join(", ");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(title)}</title>
<style>${STYLES}</style>
</head>
<body>
  <div class="wrap">
    <div class="letterhead">
      ${logo ? `<div>${logo}</div>` : ""}
      <div class="co">
        <p class="legal">${escapeHtml(c.legalName || c.brandName || "Samakaab")}</p>
        ${address ? `<p class="addr">${address}</p>` : ""}
        <p class="contact">${escapeHtml([c.phone && `Tel: ${c.phone}`, c.email && `Email: ${c.email}`].filter(Boolean).join(" · "))}</p>
      </div>
    </div>
    ${body}
    <p class="footerNote">Generated by ${escapeHtml(c.brandName || c.legalName)} on ${escapeHtml(new Date().toLocaleString())}.</p>
  </div>
</body>
</html>`;
}

export function printInventoryHtml(html) {
  const w = window.open("", "_blank");
  if (!w) return;
  w.document.write(html);
  w.document.close();
  w.focus();
  setTimeout(() => {
    w.print();
    w.close();
  }, 300);
}

function daysUntil(d) {
  if (!d) return null;
  const end = new Date(d);
  end.setHours(0, 0, 0, 0);
  const start = new Date();
  start.setHours(0, 0, 0, 0);
  return Math.round((end - start) / 86400000);
}

function statusForProduct(p, expiryDays = 30) {
  if (p.lowStock) return "Low";
  const days = daysUntil(p.nearestExpiry);
  if (days != null && days >= 0 && days <= expiryDays) return "Expiring";
  if (days != null && days < 0) return "Expired";
  return "OK";
}

function rowClass(p, expiryDays = 30) {
  const s = statusForProduct(p, expiryDays);
  if (s === "Low" || s === "Expired") return "low";
  if (s === "Expiring") return "expiring";
  return "";
}

/** @param {"all"|"low"|"expiring"|"closing"} kind */
export function buildInventoryListHtml(products, company, { kind = "all", expiryDays = 30, title } = {}) {
  const list = products || [];
  const today = new Date().toLocaleDateString();
  const lowCount = list.filter((p) => p.lowStock).length;
  const costTotal = list.reduce((s, p) => s + (Number(p.costValue) || 0), 0);
  const sellTotal = list.reduce((s, p) => s + (Number(p.sellValue) || 0), 0);

  const titles = {
    all: "INVENTORY LIST",
    low: "LOW STOCK REPORT",
    expiring: `EXPIRING SOON (within ${expiryDays} days)`,
    closing: "DAILY CLOSING SHEET",
  };
  const docTitle = title || titles[kind] || "INVENTORY";

  const isClosing = kind === "closing";
  const headCols = isClosing
    ? `<th>#</th><th>Product</th><th>Unit</th><th class="num">On hand</th><th class="num">Sold today</th><th class="num">Remaining</th>`
    : `<th>#</th><th>Product</th><th>Store</th><th>Unit</th><th class="num">Remaining</th><th class="num">Sell price</th><th>Nearest expiry</th><th>Status</th>`;

  const rows = list
    .map((p, i) => {
      if (isClosing) {
        return `<tr>
          <td>${i + 1}</td>
          <td>${escapeHtml(p.name)}</td>
          <td>${escapeHtml(inventoryUnitLabel(p.unit))}</td>
          <td class="num">${escapeHtml(String(p.quantityRemaining ?? 0))}</td>
          <td class="num"><span class="blank"></span></td>
          <td class="num"><span class="blank"></span></td>
        </tr>`;
      }
      return `<tr class="${rowClass(p, expiryDays)}">
        <td>${i + 1}</td>
        <td>${escapeHtml(p.name)}</td>
        <td>${escapeHtml(p.store || "—")}</td>
        <td>${escapeHtml(inventoryUnitLabel(p.unit))}</td>
        <td class="num">${escapeHtml(String(p.quantityRemaining ?? 0))}</td>
        <td class="num">${Number(p.sellPrice) > 0 ? escapeHtml(formatMoney(p.sellPrice)) : "—"}</td>
        <td>${p.nearestExpiry ? escapeHtml(toInputDate(p.nearestExpiry)) : "—"}</td>
        <td>${escapeHtml(statusForProduct(p, expiryDays))}</td>
      </tr>`;
    })
    .join("");

  const body = `
    <h1 class="docTitle">${escapeHtml(docTitle)}</h1>
    <p class="docSubtitle">Report date: ${escapeHtml(today)} · ${list.length} product${list.length === 1 ? "" : "s"}</p>
    ${
      !isClosing
        ? `<div class="summary">
      <div class="box"><div class="lbl">Products</div><div class="val">${list.length}</div></div>
      <div class="box"><div class="lbl">Low stock</div><div class="val">${lowCount}</div></div>
      <div class="box"><div class="lbl">Stock value (cost)</div><div class="val">${escapeHtml(formatMoney(costTotal))}</div></div>
      <div class="box"><div class="lbl">Stock value (sell)</div><div class="val">${escapeHtml(formatMoney(sellTotal))}</div></div>
    </div>`
        : `<p class="muted">Fill “Sold today” at closing, then enter those numbers in the system (Record sold).</p>`
    }
    <table class="inv">
      <thead><tr>${headCols}</tr></thead>
      <tbody>
        ${rows || `<tr><td colspan="7" class="muted">No products.</td></tr>`}
      </tbody>
    </table>`;

  return wrapHtml(docTitle, body, company);
}

