export function downloadInventoryCsv(products, filename = "inventory") {
  const header = [
    "Product",
    "Store",
    "Unit",
    "Remaining",
    "Sell price",
    "Cost value",
    "Sell value",
    "Nearest expiry",
    "Low stock",
    "Status",
  ];
  const rows = (products || []).map((p) => [
    p.name,
    p.store || "",
    inventoryUnitLabel(p.unit),
    p.quantityRemaining ?? 0,
    p.sellPrice ?? 0,
    p.costValue ?? 0,
    p.sellValue ?? 0,
    p.nearestExpiry ? toInputDate(p.nearestExpiry) : "",
    p.lowStock ? "yes" : "no",
    statusForProduct(p),
  ]);
  downloadCsv(`${safeFileSegment(filename)}.csv`, header, rows);
}

export function filterInventoryProducts(products, { filter = "all", expiryDays = 30, store = "" } = {}) {
  let list = products || [];
  if (store) list = list.filter((p) => p.store === store);
  if (filter === "low") return list.filter((p) => p.lowStock);
  if (filter === "expiring") {
    return list.filter((p) => {
      const d = daysUntil(p.nearestExpiry);
      return d != null && d <= expiryDays;
    });
  }
  return list;
}
